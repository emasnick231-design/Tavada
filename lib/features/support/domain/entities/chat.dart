import 'package:freezed_annotation/freezed_annotation.dart';

part 'chat.freezed.dart';
part 'chat.g.dart';

@JsonEnum(fieldRename: FieldRename.snake)
enum ChatAuthor { user, agent, system }

/// Client-side delivery state of an outgoing message.
enum MessageDeliveryStatus { sending, sent, failed }

/// The support agent handling the conversation ("Mollie").
@freezed
abstract class SupportAgent with _$SupportAgent {
  const factory SupportAgent({
    required String name,
    required String avatarUrl,
    @Default(true) bool isOnline,
  }) = _SupportAgent;

  factory SupportAgent.fromJson(Map<String, dynamic> json) =>
      _$SupportAgentFromJson(json);
}

@freezed
abstract class ChatMessage with _$ChatMessage {
  const factory ChatMessage({
    /// Generated by the client so optimistic bubbles keep their identity
    /// (and animation) once the server confirms them.
    required String id,
    @JsonKey(unknownEnumValue: ChatAuthor.system) required ChatAuthor author,
    required DateTime createdAt,
    String? text,

    /// Local file path of an attached photo.
    String? imagePath,
    String? authorName,
    @JsonKey(includeFromJson: false, includeToJson: false)
    @Default(MessageDeliveryStatus.sent)
    MessageDeliveryStatus deliveryStatus,
  }) = _ChatMessage;

  const ChatMessage._();

  factory ChatMessage.fromJson(Map<String, dynamic> json) =>
      _$ChatMessageFromJson(json);

  bool get isMine => author == ChatAuthor.user;
  bool get hasImage => imagePath != null && imagePath!.isNotEmpty;
}

/// The customer's conversation with support, oldest message first.
@freezed
abstract class ChatThread with _$ChatThread {
  const factory ChatThread({
    required String id,
    SupportAgent? agent,
    @Default([]) List<ChatMessage> messages,
  }) = _ChatThread;

  factory ChatThread.fromJson(Map<String, dynamic> json) =>
      _$ChatThreadFromJson(json);
}
